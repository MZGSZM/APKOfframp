#!/usr/bin/env python3
"""Builds the APK Offramp logo and its Android icon resources from one geometry.

The mark: a solid phone with a dashed road cut into its screen. Where the road leaves
the phone the colors swap, so outside it is a light road with dark dashes, ending in an
amber arrowhead. Android vector drawables cannot use masks, so the cut-outs are computed
here as plain filled outlines.

Writes:
  design/logo.svg
  app/src/main/res/drawable/ic_launcher_foreground.xml
  app/src/main/res/drawable/ic_launcher_monochrome.xml
  app/src/main/res/drawable/ic_stat_offramp.xml

Needs shapely: pip install shapely
Run from anywhere: python3 design/generate_icons.py
"""
from pathlib import Path

from shapely import affinity
from shapely.geometry import LineString, Polygon, box
from shapely.ops import substring, unary_union

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "app/src/main/res/drawable"

BG, MARK, ACCENT = "#10313B", "#E6EFEA", "#F0A63A"

# Drawing coordinates, before the final fit onto the 108 canvas.
ROAD_WIDTH = 12.0
DASH_WIDTH = 2.3
DASH_ON, DASH_OFF = 5.0, 4.5
GAP = 3.0            # clearance between the phone and the road outside it
FIT_SCALE = 0.8      # keeps everything inside the 66-unit safe circle


def rounded_rect(x, y, w, h, r):
    return box(x + r, y + r, x + w - r, y + h - r).buffer(r, quad_segs=16)


def bezier(p0, p1, p2, p3, n=240):
    pts = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        pts.append((
            u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
            u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1],
        ))
    return LineString(pts)


def dashes_along(line, width, on, off):
    parts, pos = [], 0.0
    while pos < line.length:
        seg = substring(line, pos, min(pos + on, line.length))
        if seg.length > 0.01:
            parts.append(seg.buffer(width / 2, cap_style="flat"))
        pos += on + off
    return unary_union(parts)


def arrowhead(end, ctrl, length, half, back=1.0, round_by=1.0):
    tx, ty = end[0] - ctrl[0], end[1] - ctrl[1]
    n = (tx * tx + ty * ty) ** 0.5
    tx, ty = tx / n, ty / n
    nx, ny = -ty, tx
    tip = (end[0] + length * tx, end[1] + length * ty)
    bc = (end[0] - back * tx, end[1] - back * ty)
    tri = Polygon([tip, (bc[0] + half * nx, bc[1] + half * ny), (bc[0] - half * nx, bc[1] - half * ny)])
    return tri.buffer(round_by, join_style="round", quad_segs=8)


def build():
    phone = rounded_rect(30, 26, 32, 56, 8)
    clearance = rounded_rect(30 - GAP, 26 - GAP, 32 + 2 * GAP, 56 + 2 * GAP, 8 + GAP)
    end, ctrl = (74, 42), (54, 50)
    center = bezier((42, 82), (42, 62), ctrl, end)
    road = center.buffer(ROAD_WIDTH / 2, cap_style="flat")
    dashes = dashes_along(center, DASH_WIDTH, DASH_ON, DASH_OFF)

    inside = phone.difference(road).union(dashes.intersection(phone))
    outside = road.difference(clearance).difference(dashes)
    mark = unary_union([inside, outside])
    accent = arrowhead(end, ctrl, 14, 12)

    def fit(g):
        g = affinity.translate(g, -54, -54)
        g = affinity.scale(g, FIT_SCALE, FIT_SCALE, origin=(0, 0))
        return affinity.translate(g, 54, 54)

    return fit(mark), fit(accent)


def path_data(geom):
    polys = getattr(geom, "geoms", [geom])
    out = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            out.append("M" + " L".join("%.2f,%.2f" % xy for xy in pts) + " Z")
    return " ".join(out)


def check_safe_zone(*geoms):
    worst = max(
        ((x - 54) ** 2 + (y - 54) ** 2) ** 0.5
        for g in geoms for p in getattr(g, "geoms", [g]) for x, y in p.exterior.coords
    )
    if worst > 33:
        raise SystemExit(f"Artwork reaches {worst:.1f} from center; the safe zone is 33.")
    return worst


def vector(width_dp, viewport, paths, translate=0.0):
    group_open = f'    <group android:translateX="{-translate}" android:translateY="{-translate}">\n' if translate else ""
    group_close = "    </group>\n" if translate else ""
    body = "".join(
        f'{"    " if translate else ""}    <path\n'
        f'{"    " if translate else ""}        android:fillColor="{color}"\n'
        f'{"    " if translate else ""}        android:fillType="evenOdd"\n'
        f'{"    " if translate else ""}        android:pathData="{d}" />\n'
        for color, d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by design/generate_icons.py. Edit that script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width_dp}dp"\n'
        f'    android:height="{width_dp}dp"\n'
        f'    android:viewportWidth="{viewport}"\n'
        f'    android:viewportHeight="{viewport}">\n'
        f"{group_open}{body}{group_close}"
        "</vector>\n"
    )


def main():
    mark, accent = build()
    worst = check_safe_zone(mark, accent)
    m, a = path_data(mark), path_data(accent)

    (ROOT / "design/logo.svg").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!--\n"
        "  APK Offramp logo, master artwork. Generated by design/generate_icons.py.\n"
        "  108x108 canvas matching the adaptive icon; all artwork inside the central 66-unit circle.\n"
        "  A solid phone with a dashed road cut into its screen. Past the phone's edge the colors\n"
        "  swap and the road ends in an amber arrowhead: apps leave the phone for your own server.\n"
        f"  Palette: background {BG}, mark {MARK}, accent {ACCENT}.\n"
        "-->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">\n'
        f'  <rect width="108" height="108" fill="{BG}"/>\n'
        f'  <path fill="{MARK}" fill-rule="evenodd" d="{m}"/>\n'
        f'  <path fill="{ACCENT}" fill-rule="evenodd" d="{a}"/>\n'
        "</svg>\n"
    )
    DRAWABLE.mkdir(parents=True, exist_ok=True)
    (DRAWABLE / "ic_launcher_foreground.xml").write_text(
        vector(108, 108, [("@color/logo_mark", m), ("@color/logo_accent", a)]))
    (DRAWABLE / "ic_launcher_monochrome.xml").write_text(
        vector(108, 108, [("#FFFFFFFF", m), ("#FFFFFFFF", a)]))
    # Notification icon: the 66-unit safe zone (21..87) mapped onto 24dp.
    (DRAWABLE / "ic_stat_offramp.xml").write_text(
        vector(24, 66, [("#FFFFFFFF", m), ("#FFFFFFFF", a)], translate=21))
    print(f"Wrote logo.svg and three drawables. Furthest point from center: {worst:.1f} of 33.")


if __name__ == "__main__":
    main()
